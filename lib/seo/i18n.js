export function fmt(s, vars) {
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars && k in vars ? String(vars[k]) : m));
}

// UI string in the page language, optionally with {vars} filled.
export function t(key, lang, vars) {
  let s = key;
  if (lang === "hi") s = T[key] || hs(key, "hi") || key;
  return vars ? fmt(s, vars) : s;
}

